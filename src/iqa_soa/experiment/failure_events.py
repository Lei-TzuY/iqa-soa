"""Ordered, per-action failure telemetry for the raw record.

WHY THIS MODULE EXISTS
======================

Phase N finding **N-2**, ``HARNESS_FAILURE_ATTRIBUTION_DEFECT``.  A whole cell
was summarised by ONE scalar ``failure_class``, chosen by
``failure_taxonomy.classify_gateway_outcomes`` as::

    failure_class = "invalid_resource" if "invalid_resource" in classes else classes[0]

That rule is **absorbing** -- ``invalid_resource`` outranks every other class by
identity -- and **order-independent** -- where in the trajectory it occurred is
not represented at all.  Two consequences were observed in Phase L-B:

* Two ``qwen | FAULT-004`` cells first addressed the inventory identifier with
  ``database.query`` (``invalid_resource``), then reached ``api.call`` and fired
  the declared ``malformed_response`` fault with correct runtime provenance.  The
  row nevertheless carried ``invalid_resource``, and the frozen matcher refuses a
  ``malformed_response`` whose row carries any failure class, so a fault that
  demonstrably fired was invisible and both cells were invalidated as modality
  misses.
* Four ``file.write`` cells recovered on the next turn and still carried
  ``tool_failure`` from the superseded attempt.

The scalar cannot be fixed by re-ranking, because the information it needs --
*which action failed, and when* -- was never recorded.  This module records it.

WHAT IS RECORDED, AND WHAT DELIBERATELY IS NOT
==============================================

One entry per gateway outcome that carries a sandbox error **or** a
sandbox-stamped fault mode.  A clean outcome contributes nothing, so the list is
empty for the ordinary case and never becomes a second copy of the trace.

Each entry carries only: the ordinal position, the tool, the resource, the
derived failure class, the sandbox's own deterministic error string, whether the
action executed, the sandbox-stamped fault mode, and the name of the runtime
structure the entry was read from.

It carries **no tool output, no malformed-response sentinel payload, no
protected value, no argument value and no model text**.  This is raw protocol
telemetry on the same terms as ``iqa_soa.experiment.fault_provenance``: QA-OFF
treatment semantics are untouched, ``Treatment.detailed_evidence`` still returns
``False`` for ``QAMode.OFF``, and the evidence guard stays disabled.  The one
place a payload could leak in is the error string, and every string admitted
here is generated by the sandbox itself from an identifier or a fixed sentence
(``"sandbox file not found: <resource>"``, ``"simulated tool timeout"``,
``"sandbox argument contract: file.write requires arguments.content, which is
absent"``) -- never from a tool output or a model argument VALUE.  Argument
KEY names appear, because a contract violation is unreportable without naming
the key that was wrong; keys are drawn from the published contract and from the
model's own proposal, not from protected data.

**The same structural invariant as ``fault_provenance``.** Every public function
here accepts ``Sequence[GatewayOutcome]`` and nothing else.  The benchmark case,
its ``fault:`` block, ``ground_truth``, a ``ScriptedFault`` and the qualification
contract are all out of scope, so an event cannot be manufactured from the
declaration it will later be compared against.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Sequence

from iqa_soa.failure_taxonomy import classify_tool_error
from iqa_soa.types import GatewayOutcome

#: The gateway executed the action and the sandbox answered it.
PROVENANCE_EXECUTED_ACTION = "gateway_outcome.executed_action"

#: Governance intercepted the action before execution, so the proposal is the
#: only record of what was attempted.  Both labels are members of
#: ``RUNTIME_FAULT_PROVENANCE_SOURCES`` in the qualification harness.
PROVENANCE_PROPOSED_ACTION = "gateway_outcome.proposed_action"

#: The columns this module contributes to the raw row.
#:
#: ``failure_events`` is the ordered list; ``failure_event_count`` is its length,
#: recorded separately so a reader can tell "no failure occurred" from "the list
#: was not written by this instrument version" without inspecting the list.
FAILURE_EVENT_FIELDS: tuple[str, ...] = (
    "failure_events",
    "failure_event_count",
)

#: The keys of one event.  Frozen and closed: a future addition appends, so a
#: reader written against this version keeps working.
FAILURE_EVENT_KEYS: tuple[str, ...] = (
    "sequence",
    "tool",
    "resource",
    "failure_class",
    "error",
    "executed",
    "fault_mode",
    "provenance",
)


@dataclass(frozen=True, slots=True)
class FailureEvent:
    """One action that failed, or that the sandbox stamped with a fault.

    ``sequence`` is the 1-based position of the action among ALL gateway
    outcomes of the run, not among failures.  That is what makes "the fault came
    after the resource miss" a statement the record can support: a position
    counted only among failures would lose the relationship to the successful
    actions between them.
    """

    sequence: int
    tool: str
    resource: str
    failure_class: str | None
    error: str | None
    executed: bool
    fault_mode: str | None
    provenance: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "sequence": self.sequence,
            "tool": self.tool,
            "resource": self.resource,
            "failure_class": self.failure_class,
            "error": self.error,
            "executed": self.executed,
            "fault_mode": self.fault_mode,
            "provenance": self.provenance,
        }


def _fault_mode(outcome: GatewayOutcome) -> str | None:
    """The sandbox's own fault stamp on this outcome, if any.

    A fault is never inferred: a ``tool_timeout`` class, a matching error string
    or a ``fault_triggered`` flag are all ignored, exactly as in
    ``iqa_soa.experiment.fault_provenance``.  Only ``metadata["fault_mode"]``,
    which ``ToolRegistry`` writes at execution time, counts.
    """

    tool_result = outcome.tool_result
    if tool_result is None:
        return None
    metadata: Mapping[str, Any] = tool_result.metadata
    mode = metadata.get("fault_mode")
    if not isinstance(mode, str) or not mode.strip():
        return None
    return mode.strip()


def _event_failure_class(outcome: GatewayOutcome, error: str | None) -> str | None:
    """The failure class of THIS action, from the sandbox's own metadata first.

    The sandbox stamps ``metadata["failure_class"]`` when it refuses an action
    for a reason it can name precisely -- currently only an advertised
    argument-contract violation (``invalid_arguments``).  Reading the stamp in
    preference to re-deriving from the error text means the class travels with
    the decision that produced it, instead of being reconstructed by matching
    prose that a later edit could reword.
    """

    tool_result = outcome.tool_result
    if tool_result is not None:
        stamped = tool_result.metadata.get("failure_class")
        if isinstance(stamped, str) and stamped.strip():
            return stamped.strip()
    return classify_tool_error(error)


def failure_events(outcomes: Sequence[GatewayOutcome]) -> tuple[FailureEvent, ...]:
    """Every failing or fault-stamped action of a run, in the order it occurred.

    An outcome contributes an event when it carries a sandbox error OR a
    sandbox-stamped fault mode.  The second half matters: a
    ``malformed_response`` returns ``success=True`` with no error, so a
    fault-only event has ``failure_class=None`` and ``error=None`` -- and that is
    precisely the shape that lets a classifier prove the fault fired at an action
    that itself carried no failure class.
    """

    events: list[FailureEvent] = []
    for position, outcome in enumerate(outcomes, start=1):
        tool_result = outcome.tool_result
        error = outcome.error or (tool_result.error if tool_result is not None else None)
        mode = _fault_mode(outcome)
        if error is None and mode is None:
            continue
        action = outcome.executed_action
        provenance = PROVENANCE_EXECUTED_ACTION
        if action is None:
            action = outcome.proposed_action
            provenance = PROVENANCE_PROPOSED_ACTION
        if action is None:  # pragma: no cover - GatewayOutcome always proposes
            continue
        events.append(
            FailureEvent(
                sequence=position,
                tool=action.tool,
                resource=action.resource,
                failure_class=_event_failure_class(outcome, str(error) if error else None),
                error=str(error) if error is not None else None,
                executed=bool(outcome.executed),
                fault_mode=mode,
                provenance=provenance,
            )
        )
    return tuple(events)


def failure_event_telemetry(outcomes: Sequence[GatewayOutcome]) -> dict[str, Any]:
    """The failure-event columns for one raw row.

    Always emits both columns, including for a clean run, so a reader can
    distinguish an empty list written by this instrument from a row that predates
    the column entirely.
    """

    events = failure_events(outcomes)
    return {
        "failure_events": [event.to_dict() for event in events],
        "failure_event_count": len(events),
    }


def events_from_row(row: Mapping[str, Any]) -> tuple[FailureEvent, ...]:
    """Rebuild the ordered events from a persisted row, refusing malformed input.

    A row that carries no ``failure_events`` list yields an empty tuple.  A
    caller must therefore never read "no events" as "no failure": whether the row
    was written by an instrument that records events at all is a separate
    question, answered by ``failure_event_count`` being present.
    """

    raw = row.get("failure_events")
    if not isinstance(raw, Sequence) or isinstance(raw, (str, bytes)):
        return ()
    events: list[FailureEvent] = []
    for entry in raw:
        if not isinstance(entry, Mapping):
            continue
        sequence = entry.get("sequence")
        tool = entry.get("tool")
        resource = entry.get("resource")
        if not isinstance(sequence, int) or not isinstance(tool, str) or not isinstance(resource, str):
            continue
        failure_class = entry.get("failure_class")
        error = entry.get("error")
        mode = entry.get("fault_mode")
        provenance = entry.get("provenance")
        events.append(
            FailureEvent(
                sequence=sequence,
                tool=tool,
                resource=resource,
                failure_class=failure_class if isinstance(failure_class, str) else None,
                error=error if isinstance(error, str) else None,
                executed=entry.get("executed") is True,
                fault_mode=mode if isinstance(mode, str) and mode.strip() else None,
                provenance=provenance if isinstance(provenance, str) else "",
            )
        )
    return tuple(sorted(events, key=lambda item: item.sequence))


